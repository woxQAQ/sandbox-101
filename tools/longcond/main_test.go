package main

import (
	"errors"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

func TestLongcondCommand(t *testing.T) {
	dir := t.TempDir()
	binary := filepath.Join(dir, "longcond")
	if output, err := exec.Command("go", "build", "-o", binary, ".").CombinedOutput(); err != nil {
		t.Fatalf("build: %v\n%s", err, output)
	}
	source := `package sample
func check(a, b, c, d, e bool) {
	if a && !(b || c) &&
		(d || e) {}
	for a || b || c || d || e {}
	switch {
	case a || b || c || d || e:
	}
	if a || b || c || d {}
	if accept(a || b || c || d || e) {}
}`
	file := filepath.Join(dir, "sample_test.go")
	for path, text := range map[string]string{
		file:                               source,
		filepath.Join(dir, "generated.go"): "// Code generated by fixture. DO NOT EDIT.\n" + source,
	} {
		if err := os.WriteFile(path, []byte(text), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	for _, scenario := range []struct {
		args  []string
		code  int
		lines []string
	}{
		{[]string{dir}, 1, []string{"3:5", "5:6", "7:7"}},
		{[]string{"-max", "5", file}, 0, nil},
		{[]string{filepath.Join(dir, "missing.go"), file}, 2, nil},
	} {
		output, err := exec.Command(binary, scenario.args...).CombinedOutput()
		code := 0
		if err != nil {
			var exit *exec.ExitError
			if !errors.As(err, &exit) {
				t.Fatal(err)
			}
			code = exit.ExitCode()
		}
		if code != scenario.code {
			t.Fatalf("args %v: exit %d, want %d\n%s", scenario.args, code, scenario.code, output)
		}
		if code != 2 {
			var expected strings.Builder
			for _, pos := range scenario.lines {
				expected.WriteString(file + ":" + pos + ": condition has 5 terms (max 4)\n")
			}
			if string(output) != expected.String() {
				t.Fatalf("args %v: unexpected output\n%s", scenario.args, output)
			}
		}
	}
}
